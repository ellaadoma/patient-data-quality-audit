
-- Healthcare Patient Data Quality Audit
-- Query 1: Missing values across all 28 columns

SELECT 'Id' AS field_name,
       SUM(CASE WHEN Id IS NULL OR TRIM(Id) = '' THEN 1 ELSE 0 END) AS missing_count,
       ROUND(100.0 * SUM(CASE WHEN Id IS NULL OR TRIM(Id) = '' THEN 1 ELSE 0 END) / COUNT(*), 2) AS missing_percentage
FROM patients

UNION ALL
